import { act, createElement } from "react";
import type { Root } from "react-dom/client";
import { Window } from "happy-dom";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import type { ExtensionInput } from "@/lib/extension-events";
const { dispatch, importedProps, exportProps } = vi.hoisted(() => ({ dispatch: vi.fn(), importedProps: vi.fn(), exportProps: vi.fn() }));
vi.mock("@/state/store", () => ({ useStore: () => ({ state: { bots: [{ id: "existing" }] }, dispatch }) }));
vi.mock("./ExtensionImportDialog", () => ({ ExtensionImportDialog: (props: unknown) => { importedProps(props); return null; } }));
vi.mock("./BotTemplateExportDialog", () => ({ BotTemplateExportDialog: (props: unknown) => { exportProps(props); return null; } }));
import { ExtensionHost } from "./ExtensionHost";
import { openBotTemplateExport, openExtensionImport } from "@/lib/extension-events";
let root: Root;
let deliver: (input: ExtensionInput) => void;
let dispose: ReturnType<typeof vi.fn>;
beforeEach(async () => {
  const browser = new Window();
  vi.stubGlobal("window", browser); vi.stubGlobal("document", browser.document); vi.stubGlobal("navigator", browser.navigator);
  vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
  dispose = vi.fn();
  Object.defineProperty(window, "ogb", { value: { onPackageInstall: (callback: (input: ExtensionInput) => void) => { deliver = callback; return dispose; } }, configurable: true });
  const { createRoot } = await import("react-dom/client");
  root = createRoot(document.createElement("div")); dispatch.mockReset(); importedProps.mockClear(); exportProps.mockClear();
});
afterEach(async () => { await act(async () => root.unmount()); vi.unstubAllGlobals(); });
it("preserves legacy delivery and routes typed desktop requests into a serial confirmation flow", async () => {
  const legacy = vi.fn();
  await act(async () => root.render(createElement(ExtensionHost, { disabled: false, onLegacyPackage: legacy })));
  await act(async () => deliver("https://example.test/old-team.json"));
  expect(legacy).toHaveBeenCalledWith("https://example.test/old-team.json");
  const first = { type: "bot", source: "openmausbot", id: "research" } as const;
  const second = { type: "plugin", source: "grok-bot", id: "123" } as const;
  await act(async () => deliver(first));
  expect(importedProps.mock.lastCall![0].initialInput).toEqual(first);
  await act(async () => deliver(first));
  await act(async () => deliver(second));
  expect(importedProps.mock.lastCall![0].initialInput).toEqual(first);
  await act(async () => importedProps.mock.lastCall![0].onClose());
  expect(importedProps.mock.lastCall![0].initialInput).toEqual(second);
  await act(async () => importedProps.mock.lastCall![0].onImported({ bot: { id: "created", name: "Bot" }, warnings: [] }));
  expect(dispatch).toHaveBeenCalledWith({ type: "botAdded", bot: { id: "created", name: "Bot", messages: [] } });
  await act(async () => root.unmount());
  expect(dispose).toHaveBeenCalledTimes(1);
});
it("uses the same host for manual imports and a bot's export action", async () => {
  await act(async () => root.render(createElement(ExtensionHost, { disabled: false, onLegacyPackage: vi.fn() })));
  await act(async () => openExtensionImport());
  expect(importedProps.mock.lastCall![0].initialInput).toBeUndefined();
  await act(async () => importedProps.mock.lastCall![0].onClose());
  await act(async () => openBotTemplateExport("existing"));
  expect(exportProps.mock.lastCall![0].bot.id).toBe("existing");
});
