import { chmodSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { unzipSync } from "fflate";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { DATA_DIR } from "./config.ts";
import { createImportedBot } from "./extension-create.ts";
import { exportBotTemplate } from "./extension-export.ts";
import { createExtensionHost } from "./extension-host.ts";
import { createPluginService } from "./plugin-service.ts";
import { PluginLibrary } from "./plugins.ts";
import type { BotCreateRouteDeps } from "./routes/bots-create.ts";
import { RoutineManager } from "./routines.ts";
import { installLibrarySkill } from "./skill-library.ts";
import { installSkillDirectory, listSkills, readSkillDirectory } from "./skills.ts";
import { Store } from "./store.ts";
import { readMemoryFile, writeMemoryFile } from "./workspace.ts";

const auth = {kind: "loopback" as const, scopes: ["admin" as const, "client" as const]};
const selection = () => ({instanceId: "claude", model: "claude-sonnet-5"});
const skill = (name: string) => `---\nname: ${name}\ndescription: Fixture\n---\nRun scripts/check.sh.\n`;

describe("portable bot template round trip", () => {
  let root: string;
  beforeEach(() => {rmSync(DATA_DIR, {recursive: true, force: true}); root = mkdtempSync(join(tmpdir(), "omb-template-roundtrip-"));});
  afterEach(() => rmSync(root, {recursive: true, force: true}));
  it("exports complete private and assigned skills and imports explicit contents with paused new routines", async () => {
    const store = new Store(selection);
    const source = store.createBot({name: "Source", soul: "Portable soul"});
    store.patchBot(source.id, {avatarCrop: "circle", avatarZoom: 1.5, computer: "local", approvalMode: "full"});
    const directory = join(root, "private"); mkdirSync(join(directory, "scripts"), {recursive: true});
    writeFileSync(join(directory, "SKILL.md"), skill("private-proof"));
    writeFileSync(join(directory, "scripts/check.sh"), "#!/bin/sh\necho proof"); chmodSync(join(directory, "scripts/check.sh"), 0o755);
    writeFileSync(join(directory, "asset.bin"), Buffer.from([0, 255, 9]));
    expect(installSkillDirectory(source.id, "template:fixture", directory)).not.toHaveProperty("error");
    expect(installLibrarySkill({name: "shared-proof", instructions: skill("shared-proof"), files: [{path: "SKILL.md", content: skill("shared-proof")}, {path: "reference.bin", content: "AP8J", encoding: "base64"}], source: "fixture"})).not.toHaveProperty("error");
    store.patchBot(source.id, {assignedSkills: ["shared-proof"]});
    writeMemoryFile(source.id, "Portable memory");
    const routines = new RoutineManager({file: join(root, "routines.json"), botState: () => "ready", createTask: () => null, startTurn: async () => {}});
    const originalRoutine = routines.create({botId: source.id, name: "Morning", prompt: "Inspect", schedule: {type: "daily", time: "09:00", weekdays: [1, 2, 3, 4, 5]}, enabled: true});
    const plugins = createPluginService({library: new PluginLibrary(join(root, "plugins")), store, inUse: () => false, getDefaults: () => undefined, saveDefaults: () => {}});
    const deps = {store, cfg: {newBotDefaults: {profile: {soul: "Unrelated default", approvalMode: "full"}, memory: {"MEMORY.md": "Unrelated memory"}, skills: [{name: "unrelated", text: skill("unrelated"), source: "fixture", enabled: true}]}}, hostedModels: null, maxWorkspaceBots: 100, defaultSelection: async () => selection(), checkedModelSelection: () => ({ok: true, selection: selection()}), routines: () => routines, wireBot: (bot: typeof source) => bot, cloudOwnerKey: null} as unknown as BotCreateRouteDeps;
    const exported = await exportBotTemplate({store, plugins, routines: () => routines}, source.id, {includeMemory: true, includeRoutines: true}, auth);
    const files = unzipSync(exported.bytes);
    const profile = JSON.parse(Buffer.from(files["bot.json"]!).toString("utf8"));
    expect(profile.profile).toMatchObject({soul: "Portable soul", avatarCrop: "circle", avatarZoom: 1.5});
    expect(profile.profile).not.toHaveProperty("approvalMode");
    expect(files["skills/shared-proof/reference.bin"]).toEqual(new Uint8Array([0, 255, 9]));
    const host = createExtensionHost({dataDir: root, plugins, createBot: (...args) => createImportedBot(deps, ...args)});
    const preview = await host.prepare(undefined, exported.bytes);
    expect(preview.routines[0]?.schedule).toContain('"cron"');
    const imported = await host.import(preview.id, {includeMemory: true, includeRoutines: true}, auth);
    expect(imported.botId).not.toBe(source.id);
    const target = store.bot(imported.botId!)!;
    expect(target.soul).toBe("Portable soul");
    expect(target.approvalMode).not.toBe("full");
    expect(target).toMatchObject({avatarCrop: "circle", avatarZoom: 1.5});
    expect(listSkills(target.id).map(value => [value.name, value.enabled])).toEqual([["private-proof", false], ["shared-proof", false]]);
    const restored = readSkillDirectory(target.id, "private-proof")!;
    expect(readFileSync(join(restored.directory, "asset.bin"))).toEqual(Buffer.from([0, 255, 9]));
    expect(statSync(join(restored.directory, "scripts/check.sh")).mode & 0o111).not.toBe(0);
    expect(readMemoryFile(target.id).text).toContain("Portable memory");
    const importedRoutine = routines.listRoutines().find(value => value.botId === target.id)!;
    expect(importedRoutine.id).not.toBe(originalRoutine.id);
    expect(importedRoutine.enabled).toBe(false);
    const withoutMemory = await host.prepare(undefined, exported.bytes);
    const noMemory = await host.import(withoutMemory.id, {}, auth);
    expect(readMemoryFile(noMemory.botId!).text).not.toContain("Portable memory");
    expect(readMemoryFile(noMemory.botId!).text).not.toContain("Unrelated memory");
    const grokPreview = await host.prepare(JSON.stringify({profile: {name: "Grok minimal", description: "Stay concise"}}));
    const grokResult = await host.import(grokPreview.id, {}, auth);
    expect(grokResult.bot).toMatchObject({name: "Grok minimal", title: "", description: ""});
    expect(store.bot(grokResult.botId!)?.title.trim()).toBe("");
    host.close();
  });
});
